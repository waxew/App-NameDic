package ir.asteam.namedic.history

/**
 * مدل دادهٔ یک شخصیت تاریخی.
 *
 * این مدل عمداً از مدل [NameEntry] جدا نگه داشته شده است؛ چون اطلاعات «نام» و
 * اطلاعات «شخصیت تاریخی» دو مفهوم مستقل‌اند. برای مثال معنی یک نام نباید از
 * زندگی فردی مشهور که همان نام را داشته است استنتاج شود.
 */
data class HistoricalFigure(
    /** شناسهٔ پایدار داخلی برای استفاده در کلیدهای Compose و به‌روزرسانی داده. */
    val id: String,
    /** نام رایج فارسی شخصیت. */
    val nameFa: String,
    /** نام رایج لاتین/بین‌المللی برای جستجو و تطبیق منبع. */
    val nameEn: String,
    /** دوره یا سلسله/فضای تاریخی؛ مانند هخامنشی، ساسانی یا قاجار. */
    val periodFa: String,
    /** دستهٔ کاربردی رابط؛ مانند فرمانروایان، دانشمندان یا ادبیات. */
    val categoryFa: String,
    /** سمت، نقش یا مهم‌ترین جایگاه شناخته‌شدهٔ فرد. */
    val roleFa: String,
    /** بازهٔ زمانی یا سال‌های زندگی/فرمانروایی با بیان فارسی. */
    val yearsFa: String,
    /** خلاصهٔ بازنویسی‌شده و کوتاه برای مطالعه درون برنامه. */
    val summaryFa: String,
    /** چند نکتهٔ برجسته که در صفحهٔ جزئیات به‌صورت خوانا نمایش داده می‌شوند. */
    val highlightsFa: List<String>,
    /** عنوان منبعی که کاربر در رابط مشاهده می‌کند. */
    val sourceLabel: String,
    /** نشانی مقاله/منبع اصلی برای مراجعهٔ بیشتر؛ محتوای برنامه به آن وابسته نیست. */
    val sourceUrl: String,
)
